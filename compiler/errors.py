from collections.abc import Iterable
from dataclasses import dataclass
from typing import ClassVar


@dataclass(frozen=True)
class Diagnostic:
    line: int       # starts at 1
    column: int     # starts at 1
    message: str    # just the cause, without the position, e.g. "variable 'y' no declarada"

    # Overridden by each subclass.
    kind: ClassVar[str] = "diagnóstico"
    is_error: ClassVar[bool] = True

    def __str__(self) -> str:
        """The single format: "Línea 7, columna 3: variable 'y' no declarada"."""
        return f"Línea {self.line}, columna {self.column}: {self.message}"

    def labeled(self) -> str:
        """Same format with the kind in front, for mixed lists in the demo:
        "[error semántico] Línea 7, columna 3: variable 'y' no declarada"."""
        return f"[{self.kind}] {self}"


@dataclass(frozen=True)
class CompileError(Diagnostic):
    """Base class for every error. Use LexicalError or SemanticError."""

    kind: ClassVar[str] = "error"


@dataclass(frozen=True)
class LexicalError(CompileError):
    kind: ClassVar[str] = "error léxico"


@dataclass(frozen=True)
class SemanticError(CompileError):
    kind: ClassVar[str] = "error semántico"


@dataclass(frozen=True)
class CompileWarning(Diagnostic):
    """A warning: worth showing, but the program is still valid.

    (Not called `Warning` so it does not shadow Python's built-in class.)

    Planned cases (generated by the semantic analyzer):
      - "variable 'x' declarada pero nunca usada"
      - "la variable 'x' oculta a otra declarada en la línea 2"   (shadowing)
      - "variable 'x' usada sin inicializar"
    """

    kind: ClassVar[str] = "advertencia"
    is_error: ClassVar[bool] = False


def sort_by_position(diagnostics: Iterable[Diagnostic]) -> list[Diagnostic]:
    """Order by line and column, so the report reads top to bottom like the source."""
    return sorted(diagnostics, key=lambda d: (d.line, d.column))
